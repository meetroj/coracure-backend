import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { PatientFileCategory, ReportRequestCategory } from '@prisma/client';
import {
  IsEnum,
  IsIn,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
} from 'class-validator';

import { UPLOADABLE_CATEGORIES } from '../patient-files.service';

/**
 * What the object store will be told the file is. Restricted to what a clinical
 * record actually contains: an HTML or SVG upload served back from a signed URL
 * is a script running against whoever opens it.
 */
export const ALLOWED_CONTENT_TYPES = [
  'application/pdf',
  'image/jpeg',
  'image/png',
  'image/heic',
  'image/webp',
] as const;

export class RequestFileUploadDto {
  @ApiProperty({
    enum: UPLOADABLE_CATEGORIES,
    description:
      '`medical_history` is held against you rather than one booking. A prescription PDF is generated by the platform and cannot be uploaded.',
  })
  @IsIn(UPLOADABLE_CATEGORIES)
  category!: (typeof UPLOADABLE_CATEGORIES)[number];

  @ApiProperty({ example: 'blood-report-august.pdf' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(255)
  fileName!: string;

  @ApiProperty({ enum: ALLOWED_CONTENT_TYPES })
  @IsIn(ALLOWED_CONTENT_TYPES)
  contentType!: (typeof ALLOWED_CONTENT_TYPES)[number];
}

export class ConfirmFileUploadDto {
  @ApiProperty({ enum: UPLOADABLE_CATEGORIES })
  @IsIn(UPLOADABLE_CATEGORIES)
  category!: (typeof UPLOADABLE_CATEGORIES)[number];

  @ApiProperty({ example: 'blood-report-august.pdf' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(255)
  fileName!: string;

  @ApiProperty({
    description:
      'The `storageKey` returned by the upload-url call. Only a key issued to you is accepted.',
  })
  @IsString()
  @IsNotEmpty()
  @Matches(/^patient-files\/[0-9a-f-]{36}\/[a-z_]+\/[0-9a-f-]{36}[.a-z0-9]*$/, {
    message: 'storageKey must be one this service issued',
  })
  storageKey!: string;

  @ApiPropertyOptional({
    description: 'Attaches the file to one booking (FR-6.3). Omit to hold it against your record.',
  })
  @IsOptional()
  @IsUUID()
  consultationId?: string;

  @ApiPropertyOptional({
    description: 'Answers a provider’s request, so the file arrives labelled (FR-4.9).',
  })
  @IsOptional()
  @IsUUID()
  reportRequestId?: string;
}

export class DoctorConfirmFileUploadDto {
  @ApiProperty({ enum: UPLOADABLE_CATEGORIES })
  @IsIn(UPLOADABLE_CATEGORIES)
  category!: (typeof UPLOADABLE_CATEGORIES)[number];

  @ApiProperty({ example: 'blood-report-august.pdf' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(255)
  fileName!: string;

  @ApiProperty({
    description:
      'The `storageKey` returned by the upload-url call. Only a key issued for this patient is accepted.',
  })
  @IsString()
  @IsNotEmpty()
  @Matches(/^patient-files\/[0-9a-f-]{36}\/[a-z_]+\/[0-9a-f-]{36}[.a-z0-9]*$/, {
    message: 'storageKey must be one this service issued',
  })
  storageKey!: string;

  @ApiProperty({
    description:
      'The consultation I am uploading this for. Required — unlike the patient’s own upload, a doctor’s file is always anchored to a consultation I am treating, never held against the patient’s general record.',
  })
  @IsUUID()
  consultationId!: string;
}

export class ListFilesQueryDto {
  @ApiPropertyOptional({ enum: PatientFileCategory })
  @IsOptional()
  @IsEnum(PatientFileCategory)
  category?: PatientFileCategory;

  @ApiPropertyOptional({ description: 'Only files attached to this booking' })
  @IsOptional()
  @IsUUID()
  consultationId?: string;
}

export class RaiseReportRequestDto {
  @ApiProperty({ description: 'The consultation this is raised in' })
  @IsUUID()
  consultationId!: string;

  @ApiProperty({ example: 'A recent thyroid profile', description: 'What is needed' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(160)
  title!: string;

  @ApiProperty({
    enum: ReportRequestCategory,
    description: 'A coarse bucket the app filters/groups by. `title` stays free text.',
  })
  @IsEnum(ReportRequestCategory)
  category!: ReportRequestCategory;

  @ApiPropertyOptional({
    example: 'To check whether the symptoms you described have another cause.',
    description: 'Why — shown to the patient, so the file that comes back is the right one',
  })
  @IsOptional()
  @IsString()
  @MaxLength(2000)
  reason?: string;
}
